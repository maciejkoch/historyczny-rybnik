import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import { publicCatalogSchema } from '../../functions/src/contracts/places.mjs';
import { validateCatalog } from '../../functions/src/validation.mjs';
// Build input is a single validated snapshot. Never copy private document fields.
export function publicCatalog(input) {
  return publicCatalogSchema.parse(
    validateCatalog(input)
      .filter((place) => place.published)
      .map(({ published, createdAt, ...place }) => place),
  );
}
export function generate(input) {
  const places = publicCatalog(input);
  mkdirSync('src/app/places', { recursive: true });
  writeFileSync(
    'src/app/places/catalog.generated.ts',
    `// Generated by scripts/places/prepare.mjs; do not edit.\nimport type { Place } from './place';\nexport const PLACES: readonly Place[] = ${JSON.stringify(places, null, 2)};\n`,
  );
  // Public catalogues, redirects and sitemap are served from the database at request time.
  rmSync('public/search-index.json', { force: true });
  rmSync('public/sitemap.xml', { force: true });
  const config = JSON.parse(readFileSync('firebase.dev.json', 'utf8'));
  config.hosting.public = resolve(config.hosting.public);
  config.hosting.redirects = [];
  mkdirSync('.local', { recursive: true });
  writeFileSync('.local/firebase.dev.json', JSON.stringify(config, null, 2) + '\n');
  return places;
}
